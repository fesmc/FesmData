"Folder of the figures of a dataset: docs/figures/<Dataset>."
figures_dir(dataset::AbstractString) = joinpath(REPO_DIR, "docs", "figures", dataset)

"Gallery page of a dataset, included at the end of its page (docs/datasets/<name>.qmd)."
gallery_file(dataset::AbstractString) = joinpath(figures_dir(dataset), "gallery.md")

"""
    GalleryItem

A figure of the gallery of a dataset: its heading, the PNG file (in the folder of the
figures of the dataset) and a caption.
"""
struct GalleryItem
    heading::String
    file::String
    caption::String
end

"""
    write_gallery(dataset, items; intro="")

Write the gallery page of a dataset: a section "Figures" with a heading, figure and
caption for each item (Markdown, the paths relative to docs/datasets/).
"""
function write_gallery(dataset::AbstractString, items::Vector{GalleryItem}; intro::AbstractString="")
    open(gallery_file(dataset), "w") do io
        println(io, "<!-- Generated by `julia fesmdata.jl figures $dataset` (do not edit). -->\n")
        println(io, "## Figures\n")
        isempty(intro) || println(io, intro, "\n")
        for it in items
            println(io, "### ", it.heading, "\n")
            println(io, "![", it.caption, "](../figures/$dataset/$(it.file))\n")
        end
    end
    return gallery_file(dataset)
end

"""
    figures_command(args) -> Vector{String}

`julia fesmdata.jl figures <Dataset>`: the figures of the products of a dataset and its
gallery page. Topo and Regions have their own figures; thematic datasets (remap.toml)
and records datasets (records.toml) one figure per released product, with the options
of its `figure` table (none for `figure = false`).
"""
function figures_command(args::AbstractVector)
    length(args) == 1 || error("figures: give one dataset")
    dataset = args[1]
    mkpath(figures_dir(dataset))
    items = if dataset == "Topo"
        topo_figures()
    elseif dataset == "Regions"
        return regions_figures()
    elseif is_remap_dataset(dataset)
        [product_figure(p, path -> plot_gridded(path, product_name(p), product_panels(p), something(p.variables, String[]), p.figure))
         for p in remap_products(dataset) if p.release && p.figure !== nothing]
    elseif is_records_dataset(dataset)
        [product_figure(p, path -> plot_record(path, record_path(p), p.figure)) for p in records_products(dataset)
         if p.figure !== nothing]
    else
        error("dataset $dataset has no figures (no Topo, Regions, $dataset/remap.toml or $dataset/records.toml)")
    end
    return [joinpath.(figures_dir(dataset), getfield.(items, :file)); write_gallery(dataset, items)]
end

"""
    product_figure(p, plot) -> GalleryItem

The figure of a product, `plot(path)` (which returns its caption), in the folder of the
figures of its dataset.
"""
function product_figure(p, plot)
    file = product_name(p) * ".png"
    path = joinpath(figures_dir(p.dataset), file)
    caption = plot(path)
    println("wrote $path ($(round(Int, filesize(path) / 1e3)) kB)")
    return GalleryItem(p.name, file, caption)
end

"Panels of the figure of a thematic product: one grid of each domain and its file."
product_panels(p::RemapProduct) =
    [Panel(og, joinpath(outdir(og), "$(og.grid.name)_$(product_name(p)).nc")) for og in figure_grids(product_grids(p))]
