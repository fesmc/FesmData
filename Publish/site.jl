"A released dataset on a domain: its release, the download commands, and the files of each grid (HTML)."
function record_html(io::IO, domain::AbstractString, dataset::AbstractString)
    tables, files = read_record(domain, dataset)
    release, zenodo = tables["_RELEASE"], get(tables, "_ZENODO", nothing)
    doi(d) = "<a href=\"https://doi.org/$(esc(d))\">doi:$(esc(d))</a>"
    archive = zenodo === nothing ? "" :
        zenodo["git_tag"] == release["git_tag"] ? "; $(doi(zenodo["doi"])) (all versions: $(doi(zenodo["concept_doi"])))" :
        "; archived versions: $(doi(zenodo["concept_doi"]))"
    grids = record_grids(files)
    println(io, "<div class=\"record\">")
    println(io, "<p>Version $(esc(release["version"])) ($(esc(release["date"])), ",
            "<a href=\"$(esc(release["store"]))\">packages</a>$archive). ",
            "$(length(files)) files, $(human_size(total_size(values(files)))).</p>")
    if domain == RECORDS_FOLDER
        println(io, "<pre>julia fesmdata.jl fetch $(esc(dataset)) $(esc(domain))</pre>")
    else
        println(io, "<pre>julia fesmdata.jl fetch $(esc(dataset)) $(esc(domain))     # all grids\n",
                "julia fesmdata.jl fetch $(esc(dataset)) $(esc(first(last(grids))))     # one grid</pre>")
    end
    for (grid, entries) in grids
        println(io, "<details><summary><b>$(esc(grid))</b> <span class=\"muted\">",
                "$(length(entries)) files, $(human_size(total_size(last.(entries))))</span></summary><table>")
        for (name, e) in entries
            println(io, "<tr><td><a href=\"$(esc(e["uri"]))\">$(esc(name))</a></td>",
                    "<td class=\"size\">$(human_size(get(e, "size", 0)))</td></tr>")
        end
        println(io, "</table></details>")
    end
    println(io, "</div>")
end

"""
    Catalog

What the website shows of the registry: the released datasets on each domain, (domain,
dataset) pairs in the order of the domains (../shared/domains.toml; Records last), their
versions, and the products that nests and crops get by cropping (`crop_records`).
"""
struct Catalog
    records::Vector{Tuple{String,String}}
    version::Dict{Tuple{String,String},String}
    crops::Vector{CropRecord}
    domains::Vector{String}
    rows::Dict{String,NamedTuple}
end

function Catalog()
    rows = domain_rows()
    order = [r.folder for r in rows]
    records = sort(list_records(); by=r -> (something(findfirst(==(r[1]), order), length(order) + 1), r[2]))
    tables_of = Dict(r => read_record(r...) for r in records)
    version = Dict(r => t[1]["_RELEASE"]["version"] for (r, t) in tables_of)
    crops = crop_records(Dict(r => t[2] for (r, t) in tables_of))
    domains = filter(f -> any(r -> r[1] == f, records) || any(c -> c.folder == f, crops), order)
    return Catalog(records, version, crops, domains, Dict(r.folder => r for r in rows))
end

"Domains with a release of a dataset, in order."
released_on(cat::Catalog, dataset::AbstractString) = [d for (d, s) in cat.records if s == dataset]

"Versions of a dataset on its domains, from the latest."
dataset_versions(cat::Catalog, dataset::AbstractString) =
    sort(unique(cat.version[(d, dataset)] for d in released_on(cat, dataset)); by=v -> VersionNumber(v), rev=true)

"Records datasets (released on the domain Records)."
is_records_dataset(cat::Catalog, dataset::AbstractString) = released_on(cat, dataset) == [RECORDS_FOLDER]

"""
    write_downloads(path, cat, dataset)

Write the downloads of a dataset (Markdown with HTML blocks) to `path`, which its page
includes: for each domain, its release and the files of each grid with their links;
then the nests and crops that get its products by cropping.
"""
function write_downloads(path::AbstractString, cat::Catalog, dataset::AbstractString)
    domains = released_on(cat, dataset)
    crops = filter(c -> c.dataset == dataset, cat.crops)
    mkpath(dirname(path))
    open(path, "w") do io
        println(io, GENERATED, "\n")
        println(io, "## Downloads {#downloads}\n")
        if isempty(domains)
            println(io, "*Not released yet.*")
            return
        end
        println(io, """
            Download the files with `fesmdata.jl` into `\$FESMDATA_PRODUCTS/<Domain>/<GRID>/`
            (see [Download](../download.qmd)), or one by one from the links below. All
            released datasets are listed under [Products](../products.qmd).
            """)
        if domains == [RECORDS_FOLDER]
            println(io, "```{=html}")
            record_html(io, RECORDS_FOLDER, dataset)
            println(io, "```\n")
            return
        end
        for domain in domains
            println(io, "### $domain {#$(download_anchor(domain))}\n\n```{=html}")
            record_html(io, domain, dataset)
            println(io, "```\n")
        end
        isempty(crops) && return
        println(io, """
            ### Nests and crops {#download-by-cropping}

            These nests and crops get products of $dataset by cropping those of the domain
            (or crop) that contains them: `fetch` downloads these and cuts them (see
            [Nests and crops](../download.qmd#nests-and-crops)), e.g.
            `julia fesmdata.jl fetch $dataset $(first(crops).folder)`.

            | Nest or crop | Cut from | Products |
            |---|---|---|""")
        for folder in unique(c.folder for c in crops)
            cs = filter(c -> c.folder == folder, crops)
            println(io, "| $folder | ", join((c.source for c in cs), ", "), " | ",
                    sum(length(c.products) for c in cs), " |")
        end
        println(io)
    end
    return path
end

"""
    datasets_table(io, cat, datasets, meta)

A table of datasets (Markdown): each with its title, the domains it is released on (for
records datasets, its files) and its version.
"""
function datasets_table(io::IO, cat::Catalog, datasets, meta::AbstractDict)
    records = all(s -> is_records_dataset(cat, s) || isempty(released_on(cat, s)), datasets)
    println(io, "| Dataset | Contents | $(records ? "Files" : "Domains") | Version |")
    println(io, "|---|---|---|---|")
    for s in datasets
        domains = released_on(cat, s)
        where = if isempty(domains)
            "*not released yet*"
        elseif is_records_dataset(cat, s)
            files = read_record(RECORDS_FOLDER, s)[2]
            "$(length(files)) ($(human_size(total_size(values(files)))))"
        else
            # The domains, and the nests and crops whose parent does not have the dataset
            top = filter(d -> !haskey(cat.rows, d) || cat.rows[d].kind == "domain" || !(cat.rows[d].parent in domains), domains)
            subs = length(top) < length(domains) || any(c -> c.dataset == s, cat.crops)
            join(top, ", ") * (subs ? ", with $(length(top) > 1 ? "their" : "its") nests and crops" : "")
        end
        println(io, "| [$s]($(dataset_page(s))) | $(title_case(meta[s]["title"])) | $where | ",
                join(dataset_versions(cat, s), ", "), " |")
    end
end

"""
    write_datasets(path, cat; records=false)

Write the overview of the datasets (Markdown) to `path`: a table per topic. With
`records`, the table of the records datasets only (the topic `Records`).
"""
function write_datasets(path::AbstractString, cat::Catalog; records::Bool=false)
    datasets = read_site_datasets()
    mkpath(dirname(path))
    open(path, "w") do io
        println(io, GENERATED)
        for (topic, names) in site_topics(datasets)
            records && topic != RECORDS_FOLDER && continue
            println(io, records ? "" : "\n## $topic\n")
            datasets_table(io, cat, names, datasets)
        end
    end
    return path
end

"""
    write_products(path, cat)

Write the products page (Markdown) to `path`: a table of the gridded datasets on each
domain, with their versions, linking to their downloads, and the records datasets.
"""
function write_products(path::AbstractString, cat::Catalog)
    meta = read_site_datasets()
    topics = site_topics(meta)
    gridded = [s for (_, ss) in topics for s in ss if !is_records_dataset(cat, s) && !isempty(released_on(cat, s))]
    records = [s for (_, ss) in topics for s in ss if is_records_dataset(cat, s)]
    rows = cat.rows
    mkpath(dirname(path))
    open(path, "w") do io
        println(io, GENERATED, "\n")
        println(io, "## Gridded datasets\n")
        println(io, """
            The version of each dataset on each domain, linking to its files on the page of
            the dataset. *cut*: a nest or crop gets the products of the dataset by cropping
            those of the domain (or crop) that contains it (see
            [Nests and crops](download.qmd#nests-and-crops)). Nests and crops are indented
            below their domain; inactive domains are left out (see [Domains](domains.qmd)).
            """)
        println(io, "::: {.wide-table}\n")
        println(io, "| Domain | ", join(("[$s]($(dataset_page(s))#downloads)" for s in gridded), " | "), " |")
        println(io, "|---|", repeat("---|", length(gridded)))
        for folder in filter(f -> f != RECORDS_FOLDER && rows[f].active, cat.domains)
            indent = rows[folder].kind == "domain" ? "" : "&emsp;"
            cells = map(gridded) do s
                page = dataset_page(s)
                haskey(cat.version, (folder, s)) &&
                    return "[$(cat.version[(folder, s)])]($page#$(download_anchor(folder)))"
                any(c -> c.folder == folder && c.dataset == s, cat.crops) && return "[*cut*]($page#download-by-cropping)"
                return ""
            end
            println(io, "| $indent$folder | ", join(cells, " | "), " |")
        end
        println(io, "\n:::")
        isempty(records) && return
        println(io, "\n## Records\n")
        println(io, "Non-gridded datasets (time series, sites, profiles), released on the domain ",
                "`Records` (see [Records](records_overview.qmd)).\n")
        datasets_table(io, cat, records, meta)
    end
    return path
end

"""
    write_site(docs)

Write the generated pages of the website into the folder `docs`: `_products.md`,
`_datasets.md`, `_records.md`, `_domains.md` and `_downloads/<Dataset>.md`. Returns
their paths.
"""
function write_site(docs::AbstractString)
    cat = Catalog()
    paths = [write_products(joinpath(docs, "_products.md"), cat),
             write_datasets(joinpath(docs, "_datasets.md"), cat),
             write_datasets(joinpath(docs, "_records.md"), cat; records=true),
             write_domains(joinpath(docs, "_domains.md"))]
    for s in sort(collect(keys(read_site_datasets())))
        push!(paths, write_downloads(joinpath(docs, "_downloads", "$s.md"), cat, s))
    end
    return paths
end
